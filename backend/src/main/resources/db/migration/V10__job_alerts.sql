CREATE TABLE job_alert_subscriptions (
    user_id BIGINT PRIMARY KEY REFERENCES app_users(id) ON DELETE CASCADE,
    email VARCHAR(320),
    verified BOOLEAN NOT NULL DEFAULT FALSE,
    enabled BOOLEAN NOT NULL DEFAULT FALSE,
    companies VARCHAR(4000) NOT NULL DEFAULT '',
    min_score DECIMAL(5,2) NOT NULL DEFAULT 60,
    subscribed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    evaluated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    verification_hash VARCHAR(64),
    verification_expires_at TIMESTAMP WITH TIME ZONE,
    verification_sent_at TIMESTAMP WITH TIME ZONE,
    verification_attempts INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE job_alert_deliveries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES job_alert_subscriptions(user_id) ON DELETE CASCADE,
    job_id BIGINT NOT NULL REFERENCES job_postings(id) ON DELETE CASCADE,
    state VARCHAR(20) NOT NULL,
    score DECIMAL(5,2) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    sent_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_job_alert_delivery UNIQUE(user_id, job_id)
);
CREATE INDEX idx_job_alert_delivery_pending ON job_alert_deliveries(user_id, state);
CREATE TABLE job_alert_batch_lock (
    id INTEGER PRIMARY KEY,
    locked_until TIMESTAMP WITH TIME ZONE NOT NULL
);
