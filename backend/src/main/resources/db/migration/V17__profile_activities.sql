CREATE TABLE profile_activities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id BIGINT NOT NULL REFERENCES user_profiles(id) ON DELETE CASCADE,
    kind VARCHAR(16) NOT NULL,
    title VARCHAR(200) NOT NULL,
    organization VARCHAR(200),
    description TEXT,
    started_on DATE,
    ended_on DATE,
    CONSTRAINT ck_profile_activities_kind CHECK (kind IN ('TRAINING', 'ACTIVITY'))
);
CREATE INDEX idx_profile_activities_profile_id ON profile_activities(profile_id);
