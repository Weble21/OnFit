-- User-owned analyses of postings the user typed or uploaded (decided 2026-10-18).
-- Text extracted from a file is kept as a draft until the user confirms (and possibly edits) it.
-- The uploaded file itself is never stored.
CREATE TABLE job_analysis_drafts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
    extracted_text TEXT NOT NULL,
    extraction_method VARCHAR(32) NOT NULL,
    pages INTEGER NOT NULL,
    truncated BOOLEAN NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_job_analysis_drafts_user_id ON job_analysis_drafts(user_id);
CREATE INDEX idx_job_analysis_drafts_created_at ON job_analysis_drafts(created_at);

-- One row per confirmed source text and profile version. JSON columns hold the validated AI output;
-- scores are the deterministic calculator's and are never written by the role analysis step.
CREATE TABLE job_analyses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
    input_type VARCHAR(8) NOT NULL,
    draft_id BIGINT REFERENCES job_analysis_drafts(id) ON DELETE SET NULL,
    source_text TEXT NOT NULL,
    source_hash VARCHAR(64) NOT NULL,
    profile_snapshot TEXT NOT NULL,
    profile_hash VARCHAR(64) NOT NULL,
    structured_posting TEXT NOT NULL,
    extraction_model VARCHAR(100) NOT NULL,
    extraction_prompt_version VARCHAR(50) NOT NULL,
    calculator_version VARCHAR(50) NOT NULL,
    semantic_status VARCHAR(16) NOT NULL,
    semantic_model_version VARCHAR(200) NOT NULL,
    total_score NUMERIC(5, 2) NOT NULL,
    required_score NUMERIC(5, 2) NOT NULL,
    preferred_score NUMERIC(5, 2) NOT NULL,
    semantic_score NUMERIC(5, 2) NOT NULL,
    experience_score NUMERIC(5, 2) NOT NULL,
    preference_score NUMERIC(5, 2) NOT NULL,
    score_detail TEXT NOT NULL,
    role_status VARCHAR(16) NOT NULL,
    role_analysis TEXT,
    role_model VARCHAR(100),
    role_prompt_version VARCHAR(50),
    role_error_code VARCHAR(50),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_job_analyses_input_type CHECK (input_type IN ('TEXT', 'FILE')),
    CONSTRAINT ck_job_analyses_semantic_status CHECK (semantic_status IN ('OK', 'DISABLED', 'FAILED')),
    CONSTRAINT ck_job_analyses_role_status CHECK (role_status IN ('COMPLETED', 'FAILED')),
    CONSTRAINT ck_job_analyses_total_score CHECK (total_score BETWEEN 0 AND 100),
    CONSTRAINT ck_job_analyses_required_score CHECK (required_score BETWEEN 0 AND 100),
    CONSTRAINT ck_job_analyses_preferred_score CHECK (preferred_score BETWEEN 0 AND 100),
    CONSTRAINT ck_job_analyses_semantic_score CHECK (semantic_score BETWEEN 0 AND 100),
    CONSTRAINT ck_job_analyses_experience_score CHECK (experience_score BETWEEN 0 AND 100),
    CONSTRAINT ck_job_analyses_preference_score CHECK (preference_score BETWEEN 0 AND 100)
);
CREATE INDEX idx_job_analyses_user_source ON job_analyses(user_id, source_hash, profile_hash);
CREATE INDEX idx_job_analyses_created_at ON job_analyses(created_at);
